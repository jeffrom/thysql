const keyword_names = blk: {
    var names: [keywords.len][]const u8 = undefined;
    for (keywords, 0..) |keyword, i| names[i] = keyword.name;
    break :blk names;
};

/// The longest word that a lookup can compare. Every name is shorter.
const max_word_len = 64;

comptime {
    @setEvalBranchQuota(10_000);
    for (keywords) |keyword| {
        if (keyword.name.len > max_word_len) @compileError("keyword longer than max_word_len");
    }
    for (functions) |name| {
        if (name.len > max_word_len) @compileError("function name longer than max_word_len");
    }
}

/// The keyword that `word` spells, ignoring ASCII case, or null when it is not a keyword.
pub fn find(word: []const u8) ?Keyword {
    const index = search(&keyword_names, word) orelse return null;
    return keywords[index];
}

/// True when `word` names a built-in function, ignoring ASCII case.
pub fn isFunction(word: []const u8) bool {
    return search(&functions, word) != null;
}

/// The index of `word` in the sorted `names`, comparing without case. Null when absent.
fn search(names: []const []const u8, word: []const u8) ?usize {
    if (word.len == 0 or word.len > max_word_len) return null;
    var upper: [max_word_len]u8 = undefined;
    for (word, 0..) |byte, i| upper[i] = std.ascii.toUpper(byte);
    const key = upper[0..word.len];

    var low: usize = 0;
    var high: usize = names.len;
    while (low < high) {
        const mid = low + (high - low) / 2;
        switch (std.mem.order(u8, names[mid], key)) {
            .lt => low = mid + 1,
            .gt => high = mid,
            .eq => return mid,
        }
    }
    return null;
}

test "keyword table is sorted, unique and has no lowercase names" {
    for (keywords[1..], 0..) |keyword, i| {
        try std.testing.expectEqual(std.mem.order(u8, keywords[i].name, keyword.name), .lt);
    }
    for (keywords) |keyword| {
        for (keyword.name) |byte| try std.testing.expect(!std.ascii.isLower(byte));
    }
}

test "function table is sorted and unique" {
    for (functions[1..], 0..) |name, i| {
        try std.testing.expectEqual(std.mem.order(u8, functions[i], name), .lt);
    }
}

test "find ignores ASCII case and reports reserved words" {
    const select = find("select").?;
    try std.testing.expectEqualStrings("SELECT", select.name);
    try std.testing.expect(select.reserved);
    try std.testing.expect(find("Select") != null);
    try std.testing.expect(find("SeLeCt").?.reserved);

    const account = find("account").?;
    try std.testing.expect(!account.reserved);

    try std.testing.expect(find("_FILENAME").?.reserved);
    try std.testing.expect(find("manual").?.reserved == false);
    try std.testing.expect(find("customer") == null);
    try std.testing.expect(find("") == null);
}

test "isFunction recognizes built-in names in any case" {
    try std.testing.expect(isFunction("count"));
    try std.testing.expect(isFunction("GROUP_CONCAT"));
    try std.testing.expect(isFunction("json_extract"));
    try std.testing.expect(!isFunction("values"));
    try std.testing.expect(!isFunction("customer"));
}
